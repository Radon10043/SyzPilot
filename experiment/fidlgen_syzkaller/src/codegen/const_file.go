package codegen

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/Radon10043/cloud/experiment/fidlgen_syzkaller/src/internal/fidlgen"
)

// WriteConstFile writes the companion .const file that syzkaller expects
// alongside a description file.
//
// The generated descriptions inline every constant numerically, so there is
// nothing to extract from Zircon headers and the file only has to record which
// architectures the descriptions apply to. Its format matches what syzkaller's
// own syz-extract writes, so that re-running extraction is a no-op.
func WriteConstFile(filename, arches string) error {
	var names []string
	for _, arch := range strings.Split(arches, ",") {
		if arch = strings.TrimSpace(arch); arch != "" {
			names = append(names, arch)
		}
	}
	if len(names) == 0 {
		return fmt.Errorf("no architectures given")
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# Code generated by syz-sysgen. DO NOT EDIT.\n")
	fmt.Fprintf(&buf, "arches = %s\n", strings.Join(names, ", "))
	return fidlgen.WriteFileIfChanged(filename, buf.Bytes())
}
